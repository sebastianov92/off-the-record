export type TextKey = keyof typeof es;
const table = (typeof navigator !== 'undefined' && !/^es\b/i.test(navigator.language || 'es')) ? en : es;

export function t(key: TextKey, values: Record<string, string | number> = {}): string {
  return table[key].replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}
